
function[] = make_file(r,iter,folderPath,dim)

% folderPath = "C:\Users\Admin\Desktop\output";

% numIterations = T/dt; 

    matrix = r;  
    
    filename = fullfile(folderPath, sprintf('output_%d.xyz', iter));

    % Open the file for writing
    fileID = fopen(filename, 'w');

    % Write the number of atoms (number of rows in the matrix)
    fprintf(fileID, '%d\n', size(matrix, 1));

    % Write a comment line (optional)
    fprintf(fileID, 'Generated by MATLAB\n');

    % Write each row of the matrix as x y z coordinates
    for i = 1:size(matrix, 1)
        fprintf(fileID, ' %d ', matrix(i, 1));
        for (j=1:dim)
           fprintf(fileID, ' %d ', matrix(i, j+1));
        end
        fprintf(fileID, '\n');
    end

    fclose(fileID);


